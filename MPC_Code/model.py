class Drone_Dynamics:
    def __init__(self, model_path):
        self.device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
        self.model, self.cfg, self.settings, _ = load_checkpoint(model_path, self.device)
        self.model.eval()

        #The network weights are fixed. Only gradients with respect to the state
        #and the rotor speeds are needed (for the MPC Jacobians).
        for p in self.model.parameters():
            p.requires_grad_(False)
        self.h = self.model.h
        self.hist = None
        print("Model loaded successfully.")
        print(f"Model history length needed: {self.h}")

    def set_state_history(self, com_hist, R_hist):
        self.hist = [(np.asarray(c, float), np.asarray(R, float)) for c, R in zip(com_hist, R_hist)]

    def make_tensor(self, a):
        return torch.as_tensor(np.asarray(a), dtype=torch.float32, device=self.device)


    #Force computations ----------------------------------------

    def get_propulsion_force(self, rotor_speeds, R_curr):
        #Takes in the rotor speeds and the current rotation matrix to compute the propulsion force in the world frame.
        #Uses learned k_f and k_m coefficients to compute the thrust and yaw moment generated by the rotors.
        #(known physics: T = k_f w^2, yaw moment k_m w^2)
        f_thr, tau_thr = self.model.thrust_wrench(rotor_speeds, R_curr)
        return f_thr, tau_thr

    def get_aero_force(self, com_prev, com_curr, R_prev, R_curr, rotor_speeds, wind_vector, wall_normal_vector, wall_center_point):
        #Takes in the previous and current center of mass positions, previous and current rotation matrices,
        #rotor speeds, wind vector, wall normal vector, and wall center point it will then use this information
        #to generate the features for each of the nodes in the GNN's graph representation of the drone:
        #For COM, arm, pad nodes [u, ||u||, node_type] for the rotor nodes [u, ||u||, rotor_speed, distance_to_wall, node_type]
        aero = self.model.aero_forces(com_prev, com_curr, R_prev, R_curr, rotor_speeds, wind_vector, wall_normal_vector, wall_center_point)
        return aero["F"], aero["tau"]

    def get_non_contact_accel(self, f_thr, tau_thr, f_aero, tau_aero, R_prev, R_curr):
        # Acceleration the COM would have with no contact (thrust + aero + gravity), SI units, world frame.
        #   a_nc     = (F_thr + F_aero) / m + g
        #   alpha_nc = J_w^-1 (tau_thr + tau_aero - w x J_w w),   J_w = R I R^T
        mass, dt = float(self.model.mass), float(self.model.dt)
        g = torch.tensor([0.0, 0.0, -float(self.cfg.gravity)], device=self.device)

        F_thr_N, F_aero_N = self.model.to_newtons(f_thr)[0], self.model.to_newtons(f_aero)[0]   # N
        tau_N = self.model.to_newtons(tau_thr + tau_aero)[0]                                  # N m, thrust + aero

        R = R_curr[0]
        I_body = self.model.J_body * mass                                                     # kg m^2
        J_w = R @ I_body @ R.T                                                                # world-frame inertia
        w = so3_log(R @ R_prev[0].T) / dt                                                     # rad/s, last step

        a_nc = (F_thr_N + F_aero_N) / mass + g                                                # m/s^2
        alpha_nc = torch.linalg.solve(J_w, tau_N - torch.linalg.cross(w, J_w @ w))            # rad/s^2
        return a_nc, alpha_nc


    def get_contact_forces(self, com_h, R_h, a_nc, alpha_nc, wall_normal_vector, wall_center_point):
        # Takes in the COM position and rotation history, the COM's non-contact linear and angular
        # acceleration (SI, from get_non_contact_accel), the wall normal vector, and the wall center point.
        # Inside, the model spreads the COM state to the contact nodes:
        #   node positions x_i = p + R r_i at each pose (their differences are the node velocities)
        #   node accelerations with no contact a_i = a_nc + alpha_nc x r_i + w x (w x r_i)
        # Per-node features [vel_t, vel_t-1, a_i, a_i . n, vel_t . n, dist_to_wall, wall_normal, node type]
        # -> per-node contact force (normal + friction)
        dt = float(self.model.dt)
        contact = self.model.contact_forces(com_h, R_h,
                                            (a_nc * dt ** 2).unsqueeze(0),                    # per-step units
                                            (alpha_nc * dt ** 2).unsqueeze(0),
                                            wall_normal_vector, wall_center_point)
        F_nodes = self.model.to_newtons(contact["phi"])[0]                                    # (N, 3)

        # Split each node's force into normal and friction components.
        n = wall_normal_vector[0]                                                             # (3,)
        F_normal = (F_nodes @ n)[:, None] * n
        F_friction = F_nodes - F_normal

        # Net contact wrench about the COM, world frame (computed by the model from the node lever arms).
        F_contact = self.model.to_newtons(contact["F"])[0]                                    # N
        tau_contact = self.model.to_newtons(contact["tau"])[0]                                # N m

        return dict(F_normal=F_normal, F_friction=F_friction,
                    F_contact=F_contact, tau_contact=tau_contact, gate=contact["gate"][0, :, 0])

    def rigid_body_integrator_euler(self, F_total, tau_total, com_prev, com_curr, R_prev, R_curr):
        # Total force (N) and moment about the COM (N m) -> next pose.
        # Verlet on the COM (identical to semi-implicit Euler with v_k = (p_k - p_k-1)/dt), and a
        # semi-implicit Euler step on the angular velocity using Euler's rotation equation.
        # Gravity is added here, at the COM.
        mass, dt = float(self.model.mass), float(self.model.dt)
        g = torch.tensor([0.0, 0.0, -float(self.cfg.gravity)], device=self.device)
        I_body = self.model.J_body * mass                                                     # kg m^2
        c_prev, c_curr = com_prev[0], com_curr[0]
        R0, R1 = R_prev[0], R_curr[0]

        # Translation: com_next = 2 com_curr - com_prev + (F/m + g) dt^2
        com_next = 2.0 * c_curr - c_prev + (F_total / mass + g) * dt ** 2

        # Angular velocity over the last step, from the last two attitudes
        w = so3_log(R1 @ R0.T) / dt                                                           # rad/s

        # alpha = J_w^-1 (tau - w x J_w w),   J_w = R I R^T
        J_w = R1 @ I_body @ R1.T
        alpha = torch.linalg.solve(J_w, tau_total - torch.linalg.cross(w, J_w @ w))           # rad/s^2

        # Update the angular velocity, then rotate the current attitude by it (world frame)
        w_next = w + alpha * dt
        R_next = so3_exp(w_next * dt) @ R1
        return com_next.unsqueeze(0), R_next.unsqueeze(0)


    def propagate_state(self, state_vector, rotor_speeds, wall_normal_vector, wall_center_point, wind_vector=None):
        #State_vector: [COM_position, COM_velocity, Quaternion, Angular_velocity, Previous_velocity, Previous_angular_velocity]: 19 states

        COM_position = state_vector[0:3]
        COM_velocity = state_vector[3:6]
        Quaternion = state_vector[6:10]
        Angular_velocity = state_vector[10:13]
        Previous_velocity = state_vector[13:16]
        Previous_angular_velocity = state_vector[16:19]

        COM_Pos_km1 = COM_position - COM_velocity * self.dt
        COM_Pos_km2 = COM_Pos_km1 - Previous_velocity * self.dt

        R_curr = quat_to_rot_matrix(Quaternion)
        R_km1 = so3_exp(-Angular_velocity * self.dt) @ R_curr
        R_km2 = so3_exp(-Previous_angular_velocity * self.dt) @ R_km1

        com_history = torch.stack([COM_Pos_km2, COM_Pos_km1, COM_position])
        R_history = torch.stack([R_km2, R_km1, R_curr])
        
        if wind_vector is None:
            wind_vector = torch.zeros(3, device=self.device)

        #Takes the current COM position and recenters everything around it. 
        #This is needed because the model was trained on relative positions rather than absolute positions.
        anchor = com_history[-1].detach()

        #Recalculates the COM history based on the current COM position.
        com_history_recentered = []
        for c in com_history:
            c = c - anchor
            com_history_recentered.append(c.unsqueeze(0))
        com_history = torch.cat(com_history_recentered, dim=0)

        R_history_unsqueezed = []
        for R in R_history:
            R_history_unsqueezed.append(R.unsqueeze(0))
        R_history = torch.cat(R_history_unsqueezed, dim=0)

        #unpack inputs, wind, wall normal, and wall center point for the model
        u = rotor_speeds.unsqueeze(0)
        wind = wind_vector.unsqueeze(0)
        n = wall_normal_vector.unsqueeze(0)
        p_wall = (wall_center_point - anchor).unsqueeze(0)
        #com_prev, com_curr, R_prev, R_curr = com_history[-2], com_history[-1], R_history[-2], R_history[-1]

        # Thrust and yaw moment from the rotors (per-step units)
        f_thr, tau_thr = self.get_propulsion_force(u, R_history[-1])

        # Drag from the aero GNN, summed over the aero nodes (per-step units)
        f_aero, tau_aero = self.get_aero_force(com_history, R_history, u, wind, n, p_wall)

        # Acceleration of the COM with no contact (thrust + aero + gravity), m/s^2 and rad/s^2
        a_nc, alpha_nc = self.get_non_contact_accel(f_thr, tau_thr, f_aero, tau_aero, R_history)

        # Normal and friction force on every contact node, and their net force and moment (N, N m).
        # The contact GNN gets the COM state and the COM's non-contact acceleration.
        contact = self.get_contact_forces(com_history, R_history, a_nc, alpha_nc, n, p_wall)

        # Sum every force and moment in Newtons (gravity is added inside the integrator)
        F_thr_N, tau_thr_N = self.model.to_newtons(f_thr)[0], self.model.to_newtons(tau_thr)[0]
        F_aero_N, tau_aero_N = self.model.to_newtons(f_aero)[0], self.model.to_newtons(tau_aero)[0]
        F_total = F_thr_N + F_aero_N + contact["F_contact"]
        tau_total = tau_thr_N + tau_aero_N + contact["tau_contact"]

        com_next, R_next = self.rigid_body_integrator_euler(F_total, tau_total, com_history, R_history)

        forces = dict(F_thrust=F_thr_N, F_aero=F_aero_N,
                      **{k: v for k, v in contact.items() if k != "gate"})
        return com_next[0] + anchor, R_next[0], forces

    # ------------------------------------------------------------------
    # Rollout and linearization for the MPC
    # ------------------------------------------------------------------

    @torch.no_grad()
    def rollout(self, com_h, R_h, U, wall_normal_vector, wall_center_point, wind_vector=None):
        # Rolls the model forward over a horizon with rotor-speed sequence U (N, 4).
        # Returns the predicted COM (N, 3) and attitude (N, 3, 3) trajectories, and the pose
        # history at every step (needed to linearize along the trajectory).
        com_h, R_h = com_h.clone(), R_h.clone()
        coms, Rs, hists = [], [], []
        for u in U:
            hists.append((com_h.clone(), R_h.clone()))
            com_n, R_n, _ = self.step_torch(com_h, R_h, u, wall_normal_vector, wall_center_point, wind_vector)
            com_h = torch.cat([com_h[1:], com_n.unsqueeze(0)])
            R_h = torch.cat([R_h[1:], R_n.unsqueeze(0)])
            coms.append(com_n)
            Rs.append(R_n)
        return torch.stack(coms), torch.stack(Rs), hists

    def linearize(self, com_h, R_h, u, wall_normal_vector, wall_center_point, wind_vector=None):
        # Jacobians of the one-step map about a nominal pose history and rotor speeds.
        # Error state (18): [dp, dtheta] for each of the h = 3 poses, oldest -> newest, with the
        # attitude perturbed in the tangent space (world frame): R = exp(dtheta^) R_nominal.
        # Error input (4): du on the rotor speeds.
        # Returns the full shift-register matrices, so  dx_k+1 = A dx_k + B du_k :
        #   A = [[0 I 0], [0 0 I], [A_new]],  B = [[0], [0], [B_new]]   (18 x 18, 18 x 4)
        # plus the nominal next pose.
        h = com_h.shape[0]
        with torch.no_grad():
            com_nom, R_nom, _ = self.step_torch(com_h, R_h, u, wall_normal_vector, wall_center_point, wind_vector)

        def next_pose_error(dx, du):
            d = dx.view(h, 6)
            com_p = com_h + d[:, :3]
            R_p = so3_exp(d[:, 3:]) @ R_h
            com_n, R_n, _ = self.step_torch(com_p, R_p, u + du, wall_normal_vector, wall_center_point, wind_vector)
            return torch.cat([com_n - com_nom, so3_log(R_n @ R_nom.T)])                      # (6,)

        dx0 = torch.zeros(6 * h, device=self.device)
        du0 = torch.zeros(u.shape[0], device=self.device)
        A_new, B_new = torch.autograd.functional.jacobian(next_pose_error, (dx0, du0))        # (6, 18), (6, 4)

        n_x = 6 * h
        A = torch.zeros(n_x, n_x, device=self.device)
        A[:n_x - 6, 6:] = torch.eye(n_x - 6, device=self.device)                              # shift the history
        A[n_x - 6:] = A_new
        B = torch.zeros(n_x, u.shape[0], device=self.device)
        B[n_x - 6:] = B_new
        return A, B, com_nom, R_nom

    # ------------------------------------------------------------------
    # Numpy convenience wrapper (plant simulation / plotting, no gradients)
    # ------------------------------------------------------------------

    @torch.no_grad()
    def step(self, rotor_speeds, wall_normal_vector, wall_center_point, wind_vector=(0.0, 0.0, 0.0)):
        # Uses the stored history (set_state_history) to predict the next pose, then pushes the
        # new pose onto the history, so calling step() repeatedly rolls the drone forward.
        com_h = self.make_tensor([c for c, _ in self.hist])
        R_h = self.make_tensor([R for _, R in self.hist])
        com_n, R_n, f = self.step_torch(com_h, R_h, self.make_tensor(rotor_speeds),
                                        self.make_tensor(wall_normal_vector), self.make_tensor(wall_center_point),
                                        self.make_tensor(wind_vector))

        com_next = com_n.double().cpu().numpy()
        R_next = orthonormalize(R_n.double().cpu().numpy())
        self.hist = self.hist[1:] + [(com_next, R_next)]

        out = dict(com=com_next, R=R_next)
        out.update({k: v.cpu().numpy() for k, v in f.items()})
        return out